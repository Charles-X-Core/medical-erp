-- V44: Timezone architecture migration
-- Convert all DATETIME columns to TIMESTAMP for Instant-backed entities.
-- TIMESTAMP stores internally as UTC, which aligns with java.time.Instant.
-- Since the DB is virgin for patient data, no data loss risk.

-- Citas
ALTER TABLE citas
  MODIFY COLUMN created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  MODIFY COLUMN updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  MODIFY COLUMN inicio_atencion TIMESTAMP NULL,
  MODIFY COLUMN fin_atencion TIMESTAMP NULL,
  MODIFY COLUMN asistio_confirmed_at TIMESTAMP NULL,
  MODIFY COLUMN cancelado_at TIMESTAMP NULL;

